def _r1_final(path, a):
    """R1 (ContrastCS + RC-mix) read once at N on a fixed design, tool_return minus config (Prop 5b)."""
    import fixed_design as FD
    from riskcert import ContrastCS
    out = {}
    for m, ds in FD.paired_units(FD._first_rows(path), "tool_return", "config").items():
        cs = ContrastCS(a)
        for x in ds:
            cs.update((x + 1) / 2, 0.5)  # (xa - xb + 1)/2 with xa - xb = x
        out[m] = cs.interval()
    return out


