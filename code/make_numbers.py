def rq1_macros(c2):
    """RQ1 from the preregistered session-B certification (results/c2.json, R1')."""
    p = {}
    for r in c2["rows"]:
        p.setdefault(r["model"], {})[r["a"]] = r["p_a"]
        p.setdefault(r["model"], {})[r["b"]] = r["p_b"]
    top = {m: max(v, key=v.get) for m, v in p.items()}
    by = {}
    for r in c2["rows"]:
        if r["r1p"] in (">", "<"):
            by.setdefault((r["a"], r["b"]), {})[r["model"]] = r["r1p"]
    within = cross = 0
    for ms in by.values():
        ups = [m for m, s in ms.items() if s == ">"]
        dns = [m for m, s in ms.items() if s == "<"]
        for u in ups:
            for d in dns:
                within += FAMILY[u] == FAMILY[d]
                cross += FAMILY[u] != FAMILY[d]
    return [f"\\newcommand{{\\rqOneTr}}{{{sum(v == 'tool_return' for v in top.values())}}}",
            f"\\newcommand{{\\rqOneCf}}{{{sum(v == 'config' for v in top.values())}}}",
            f"\\newcommand{{\\rqOneRev}}{{{within + cross}}}", f"\\newcommand{{\\rqOneRevWithin}}{{{within}}}"]


